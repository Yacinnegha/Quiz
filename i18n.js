let uiLang = "ar";

function loadUiLang() {
  try {
    const saved = localStorage.getItem(UI_LANG_KEY);
    if (saved === "en" || saved === "ar") return saved;
  } catch {}
  return "ar";
}

function getUiLang() {
  return uiLang;
}

function isEn() {
  return uiLang === "en";
}

function getUiLocale() {
  return uiLang === "en" ? "en-US" : "ar";
}

function t(key, params) {
  const dict = I18N[uiLang] || I18N.ar;
  let str = dict[key];
  if (str === undefined) str = I18N.ar[key];
  if (str === undefined) return key;
  if (params && typeof str === "string") {
    for (const k of Object.keys(params)) {
      str = str.replaceAll("{" + k + "}", String(params[k]));
    }
  }
  return str;
}

function getDefaultListDisplayName(list) {
  if (list && (list.builtin || list.id === "default")) return t("default_list_name");
  return list ? list.name : t("default_list_name");
}

function applyStaticTranslations() {
  const lang = getUiLang();
  const dir = lang === "ar" ? "rtl" : "ltr";
  document.documentElement.lang = lang;
  document.documentElement.dir = dir;
  document.title = t("page_title");
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute("content", t("page_desc"));

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (key) node.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    const key = node.getAttribute("data-i18n-html");
    if (key) node.innerHTML = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.getAttribute("data-i18n-placeholder");
    if (key) node.setAttribute("placeholder", t(key));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((node) => {
    const key = node.getAttribute("data-i18n-title");
    if (key) node.setAttribute("title", t(key));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.getAttribute("data-i18n-aria");
    if (key) node.setAttribute("aria-label", t(key));
  });
  document.querySelectorAll("[data-i18n-preset]").forEach((node) => {
    const key = node.getAttribute("data-i18n-preset");
    if (key) node.setAttribute("data-preset", t(key));
  });

  const lbl = document.getElementById("lang-toggle-label");
  if (lbl) lbl.textContent = t("lang_toggle_label");
}
